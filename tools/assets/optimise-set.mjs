// The placeholder art at a sensible weight (WP-QA13): every PNG over 150 KB in inbound/Placeholder Assets (terrain
// surfaces at 1-2 MB each, biome and hero art) gets a WebP copy under assets/sprites/set/, same path plus .webp, at
// the same size; convoy/set-optimised.js lists them so the loader (convoy/sprite-art.js) takes the copy. The owner's
// originals in inbound/ are not touched.
//   node tools/assets/optimise-set.mjs
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'inbound/Placeholder Assets',
  OUT = 'assets/sprites/set',
  LIMIT = 150 * 1024;
const walk = d =>
  fs.readdirSync(d, {withFileTypes: true}).flatMap(e => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

const done = [];
let before = 0,
  after = 0;
for (const f of walk(SRC)
  .filter(f => f.endsWith('.png') && fs.statSync(f).size > LIMIT)
  .sort()) {
  const rel = path.relative(SRC, f).split(path.sep).join('/');
  const out = path.join(OUT, rel + '.webp');
  fs.mkdirSync(path.dirname(out), {recursive: true});
  await sharp(f).webp({quality: 82, alphaQuality: 90, effort: 5}).toFile(out);
  before += fs.statSync(f).size;
  after += fs.statSync(out).size;
  done.push(rel);
}
fs.writeFileSync(
  'convoy/set-optimised.js',
  `// Generated by tools/assets/optimise-set.mjs: placeholder-set images with a WebP copy under assets/sprites/set/.\nexport const OPTIMISED = new Set(${JSON.stringify(done, null, 1)});\n`,
);
console.log(`${done.length} images: ${(before / 1e6).toFixed(1)} MB as PNG, ${(after / 1e6).toFixed(1)} MB as WebP`);

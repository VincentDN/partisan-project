// Build outbound/sketchfab-download.py: the bulk downloader as ONE standalone file with the model list embedded, so the
// owner can download just that file and run it anywhere. Re-run after changing sketchfab-sources.json or the script:
//   node tools/assets/build-outbound-downloader.mjs        (a test fails if outbound/ is stale)
import fs from 'node:fs';

const src = fs.readFileSync('tools/assets/sketchfab-bulk-download.py', 'utf8');
const manifest = fs.readFileSync('tools/assets/sketchfab-sources.json', 'utf8').trim();

export function build() {
  let out = src.replace(
    'SOURCES = HERE / "sketchfab-sources.json"',
    `# The model list is embedded so this file works on its own (generated by tools/assets/build-outbound-downloader.mjs).\nSOURCES_JSON = r'''${manifest}'''`,
  );
  out = out.replace('sources = json.loads(SOURCES.read_text())["sources"]', 'sources = json.loads(SOURCES_JSON)["sources"]');
  // Standalone default: the repo's inbound/sketchfab when run inside a clone, otherwise ./sketchfab-models next to the file.
  out = out.replace(
    'REPO = HERE.parent.parent\n',
    'REPO = HERE.parent if (HERE.parent / "inbound").is_dir() else None  # a clone of the repository, if run from one of its folders\nDEFAULT_OUT = (REPO / "inbound" / "sketchfab") if REPO else Path.cwd() / "sketchfab-models"\n',
  );
  out = out.replace(
    'default=str(REPO / "inbound" / "sketchfab"), help="where to put them (default: inbound/sketchfab)"',
    'default=str(DEFAULT_OUT), help="where to put them (default: inbound/sketchfab in a clone, else ./sketchfab-models)"',
  );
  out = out.replace(
    'Run it from your local clone of the repository (Python 3.8+, no extra packages):',
    'Standalone: save this one file anywhere and run it (Python 3.8+, no extra packages). Inside a clone it fills\ninbound/sketchfab, elsewhere ./sketchfab-models:',
  );
  out = out.replaceAll('python3 tools/assets/sketchfab-bulk-download.py', 'python3 sketchfab-download.py');
  out = out.replace(
    'Afterwards commit and push the new folder so the next agent session can import it:\n\n    git add inbound/sketchfab && git commit -m "Sketchfab sources" && git push',
    'Afterwards put the models in the repository so the next agent session can import them. In a clone:\n\n    git add inbound/sketchfab && git commit -m "Sketchfab sources" && git push\n\nOtherwise copy the sketchfab-models folder to inbound/sketchfab in your clone (rename it) and do the same.',
  );
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync('outbound/sketchfab-download.py', build(), {mode: 0o755});
  console.log('wrote outbound/sketchfab-download.py');
}
